package com.sschr15.mods.menubar.mixin;

import com.sschr15.mods.menubar.DebugMenu;
import net.minecraft.client.renderer.entity.EntityRenderDispatcher;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(EntityRenderDispatcher.class)
public abstract class EntityRenderDispatcherMixin {
    @Inject(method = "setRenderHitBoxes", at = @At("HEAD"))
    private void updateHitboxOption(boolean debugBoundingBox, CallbackInfo ci) {
        DebugMenu.updateRenderHitboxes(debugBoundingBox);
    }
}
